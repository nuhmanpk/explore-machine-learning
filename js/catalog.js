window.findTopic = (id) => window.CATALOG.find((t) => t.id === id);
window.findDemo = (demoId) => {
  for (let ti = 0; ti < window.CATALOG.length; ti++) {
    const t = window.CATALOG[ti];
    const i = t.demos.findIndex((d) => d.id === demoId);
    if (i >= 0) return { topic: t, demo: t.demos[i], index: i, chapter: ti };
  }
  return null;
};
// Flat list of every lesson in course order.
window.allLessons = () => {
  const out = [];
  window.CATALOG.forEach((t, ti) => t.demos.forEach((d, i) => out.push({ t, d, chapter: ti, lesson: i + 1 })));
  return out;
};

